"""REFEREE-01: the spell coverage list (GM 2026-10-22: does the engine follow "all aspects of the rules"?). For every SRD
5.2.1 spell: whether a player can cast it in Play live, whether the simulator plays it, or whether the GM rules it; and
what the rule sheet could not read from its text. Writes docs/development/SPELL_COVERAGE.md.

  py tools/spell_coverage.py
"""
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "sim"), str(ROOT / "tools"), str(ROOT / "mythastria_core")]
import spell_rules  # noqa: E402

OUT = ROOT / "docs" / "development" / "SPELL_COVERAGE.md"


def main():
    rows = spell_rules.coverage()
    count = Counter(r["status"] for r in rows)
    lines = ["# Spell coverage (REFEREE-01)", "",
             "Generated by `tools/spell_coverage.py` from the SRD 5.2.1 rule sheet (`sim/spells/srd_spells.json`). "
             "Played in Play live: a player can cast it. Simulator only: the scripted party or a creature uses it. The "
             "referee checks both. Not yet: the GM rules it at the table. Unread: what the rule sheet could not read from the text.", "",
             "| | Spells |", "|---|---|"]
    for k in ("played in Play live", "simulator only", "not yet (the GM rules it)"):
        lines.append("| %s | %d |" % (k, count[k]))
    lines += ["| all | %d |" % len(rows), ""]
    level = None
    for r in rows:
        if r["level"] != level:
            level = r["level"]
            lines += ["", "## %s" % ("Cantrips" if level == 0 else "Level %d" % level), "", "| Spell | Status | Unread |", "|---|---|---|"]
        lines.append("| %s | %s | %s |" % (r["name"], r["status"], "; ".join(r["unread"]) or ""))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s: %s" % (OUT.relative_to(ROOT), dict(count)))


if __name__ == "__main__":
    main()
